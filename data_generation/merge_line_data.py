"""
merge_line_data.py
=====================
Merges the newly-regenerated line-fault data (from
generate_data_line_only.py) with your EXISTING, already-trusted gen-trip
and load-fault data -- so you get one combined, corrected dataset without
regenerating the 330 gen/load scenarios you already have.

This only works cleanly if your existing data was generated with the SAME
X_train_cols/Y_train_cols layout as generate_data_v9.py (5 and 15 columns
respectively) -- true for anything generated by generate_data_v8.py or
generate_data_v9.py.

Usage:
    python merge_line_data.py \\
        --old_dir training_data_v5 \\
        --line_dir training_data_line_only \\
        --out_dir training_data_merged

--old_dir should be whatever directory holds your EXISTING X_train.npy /
Y_train.npy / meta.json (the ones with gen+load+old-broken-line data).
This script filters OUT the old line-fault rows (fault_type_id == 2) from
that directory before merging in the new, corrected line-fault rows --
so you don't end up with duplicate or conflicting line-fault data.
"""

import argparse
import json
import os
import numpy as np

parser = argparse.ArgumentParser()
parser.add_argument('--old_dir',  type=str, required=True,
                     help='Directory with existing X_train.npy/Y_train.npy/meta.json')
parser.add_argument('--line_dir', type=str, default='training_data_line_only',
                     help='Directory with the newly-regenerated line-fault data')
parser.add_argument('--out_dir',  type=str, default='training_data_merged')
args = parser.parse_args()

os.makedirs(args.out_dir, exist_ok=True)

# ── load both datasets ──
X_old = np.load(os.path.join(args.old_dir, 'X_train.npy'))
Y_old = np.load(os.path.join(args.old_dir, 'Y_train.npy'))
stable_old = np.load(os.path.join(args.old_dir, 'stable_labels.npy'))
with open(os.path.join(args.old_dir, 'meta.json')) as f:
    meta_old = json.load(f)

X_line = np.load(os.path.join(args.line_dir, 'X_train.npy'))
Y_line = np.load(os.path.join(args.line_dir, 'Y_train.npy'))
stable_line = np.load(os.path.join(args.line_dir, 'stable_labels.npy'))
with open(os.path.join(args.line_dir, 'meta.json')) as f:
    meta_line = json.load(f)

print(f"Old dataset : X={X_old.shape}  Y={Y_old.shape}")
print(f"New line data: X={X_line.shape}  Y={Y_line.shape}")

# ── filter OUT old (broken) line-fault rows: fault_type_id column index 3 ──
FAULT_TYPE_COL = 3
LINE_TYPE_ID = 2.0
keep_mask = X_old[:, FAULT_TYPE_COL] != LINE_TYPE_ID
n_removed = (~keep_mask).sum()
print(f"Removing {n_removed} old line-fault rows from --old_dir data "
      f"(includes the broken t_clear=0.1 scenarios)")

X_old_filtered = X_old[keep_mask]
Y_old_filtered = Y_old[keep_mask]
stable_old_filtered = stable_old[keep_mask]

# ── concatenate ──
X_merged = np.concatenate([X_old_filtered, X_line], axis=0)
Y_merged = np.concatenate([Y_old_filtered, Y_line], axis=0)
stable_merged = np.concatenate([stable_old_filtered, stable_line], axis=0)

print(f"\nMerged dataset: X={X_merged.shape}  Y={Y_merged.shape}")

assert not np.any(np.isnan(X_merged)), "NaN in merged X_train!"
assert not np.any(np.isnan(Y_merged)), "NaN in merged Y_train!"

np.save(os.path.join(args.out_dir, 'X_train.npy'), X_merged)
np.save(os.path.join(args.out_dir, 'Y_train.npy'), Y_merged)
np.save(os.path.join(args.out_dir, 'stable_labels.npy'), stable_merged)

# ── merged meta.json: combine counts, keep the newer line-fault grid ──
meta_merged = dict(meta_old)  # start from old meta (has gen/load grids etc.)
meta_merged['t_clears_line'] = meta_line['t_clears_line']  # the FIXED grid
meta_merged['lines_tested'] = meta_line['lines_tested']
# Scenario-level (not row-level) stable/unstable counts, kept separate per
# source since gen/load and line data came from different meta.json files.
meta_merged['gen_load_n_stable_scenarios'] = meta_old.get('n_stable')
meta_merged['gen_load_n_unstable_scenarios'] = meta_old.get('n_unstable')
meta_merged['line_n_stable_scenarios'] = meta_line.get('n_stable')
meta_merged['line_n_unstable_scenarios'] = meta_line.get('n_unstable')
meta_merged['n_failed'] = meta_line.get('n_failed', 0)  # old line failures are gone now
meta_merged['failed'] = meta_line.get('failed', [])
meta_merged['X_shape'] = list(X_merged.shape)
meta_merged['Y_shape'] = list(Y_merged.shape)
meta_merged['note'] = ("Merged dataset: gen+load rows from --old_dir, line-fault rows "
                        "regenerated with the fixed t_clear grid (0.1->0.25). "
                        "See generate_data_line_only.py for details on the fix.")

with open(os.path.join(args.out_dir, 'meta.json'), 'w') as f:
    json.dump(meta_merged, f, indent=2)

print(f"\nSaved merged dataset to ./{args.out_dir}/")
print(f"  X_train.npy       {X_merged.shape}")
print(f"  Y_train.npy       {Y_merged.shape}")
print(f"  stable_labels.npy {stable_merged.shape}")
